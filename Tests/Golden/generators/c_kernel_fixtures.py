import _golden; numpy, scipy = _golden.oracle()  # before any other SciPy import

"""Reference values for the tests of the C kernels (M2), from SciPy (STG-2).

    python3 Tests/Golden/generators/c_kernel_fixtures.py

writes Tests/CZTronDSPTests/KernelFixtures.swift, a file of Swift constants: the Butterworth
cascades the biquad kernels are tested with, the frequency response the double-precision kernel
is held to, and the Kaiser low-pass filters of the rate changers. Every library argument is
passed explicitly; the output is deterministic.
"""

import math
import os

from scipy import signal

import _oracle

# What this generator writes outside a Golden folder, relative to the package: the golden runner
# (Scripts/golden.sh) records it in the manifest.
OUTPUTS = ["Tests/CZTronDSPTests/KernelFixtures.swift"]
OUTPUT = os.path.join(_golden.ROOT, *OUTPUTS[0].split("/"))

# name, response, sample rate, cutoff, order.
ACCEPTANCE = [
    # The fixture of WP-208, and the same filter a tenth of an octave up (WP-209).
    ("hp-1kHz-48k-order4", "highPass", 48_000.0, 1_000.0, 4),
    ("hp-1kHz-48k-order4-tenth-octave-up", "highPass", 48_000.0, 1_000.0 * 2.0 ** 0.1, 4),
    # The other orders of E-30's first figure.
    ("hp-1kHz-48k-order2", "highPass", 48_000.0, 1_000.0, 2),
    ("hp-1kHz-48k-order6", "highPass", 48_000.0, 1_000.0, 6),
    ("hp-1kHz-48k-order8", "highPass", 48_000.0, 1_000.0, 8),
]

# The filters of the stress-fixture library (WP-016), by the names it gives them. The test suite
# checks this table against StressFixture.filtersNearZero and filtersNearNyquist.
STRESS = [
    ("hp-90Hz-48k-order8", "highPass", 48_000.0, 90.0, 8),
    ("hp-20Hz-96k-order8", "highPass", 96_000.0, 20.0, 8),
    ("lp-10Hz-192k-order8", "lowPass", 192_000.0, 10.0, 8),
    ("hp-10Hz-44k1-order2", "highPass", 44_100.0, 10.0, 2),
    ("lp-0.45fs-48k-order8", "lowPass", 48_000.0, 21_600.0, 8),
    ("hp-0.45fs-44k1-order4", "highPass", 44_100.0, 19_845.0, 4),
    ("lp-0.49fs-48k-order2", "lowPass", 48_000.0, 23_520.0, 2),
]

# Where the response of the 20 Hz, order 8 high-pass at 96 kHz is checked (WP-211): from 48 dB
# down in the stop band, through the corner, to the top of the pass band.
RESPONSE_FREQUENCIES = [10.0, 12.0, 14.0, 16.0, 18.0, 20.0, 22.0, 25.0, 30.0, 40.0, 60.0, 100.0, 1_000.0, 10_000.0, 40_000.0]

# Decimation and interpolation factors the rate changers are tested with.
FACTORS = [2, 3, 4]
REJECTION = 80.0          # dB, from the new Nyquist frequency up (§6.12)
PASS_BAND = 0.8           # of the new Nyquist frequency


def butterworth(response, sample_rate, cutoff, order):
    sos = signal.butter(N=order, Wn=cutoff, btype={"highPass": "highpass", "lowPass": "lowpass"}[response],
                        analog=False, output="sos", fs=sample_rate)
    rows = []
    for b0, b1, b2, a0, a1, a2 in sos:
        if a0 != 1.0:
            raise ValueError("a section is not normalised")
        rows.append([float(b0), float(b1), float(b2), float(a1), float(a2)])
    return sos, rows


def kaiser_low_pass(factor):
    """A Kaiser windowed sinc whose stop band starts at the new Nyquist frequency, 1 / factor of
    the old one, with at least REJECTION dB there and above. Frequencies are in units of the old
    Nyquist frequency (fs = 2)."""
    stop = 1.0 / factor
    width = (1.0 - PASS_BAND) * stop
    ripple = REJECTION
    while True:
        taps_count, beta = signal.kaiserord(ripple=ripple, width=width)
        taps_count |= 1  # odd: a whole number of samples of delay
        taps = signal.firwin(numtaps=taps_count, cutoff=stop - width / 2.0, width=None, window=("kaiser", beta),
                             pass_zero=True, scale=True, fs=2.0)
        frequencies = numpy.linspace(stop, 1.0, 4_001)
        _, response = signal.freqz(b=taps, a=1.0, worN=frequencies, whole=False, fs=2.0)
        achieved = -20.0 * math.log10(float(numpy.max(numpy.abs(response))))
        if achieved >= REJECTION:
            return taps_count, float(beta), [float(t) for t in taps], achieved
        ripple += 1.0  # the estimate fell short: ask for a little more


def swift_doubles(values, indent, per_line=4):
    lines = []
    for start in range(0, len(values), per_line):
        lines.append(indent + ", ".join(repr(float(v)) for v in values[start:start + per_line]) + ",")
    return "\n".join(lines)


def cascade_literal(name, response, sample_rate, cutoff, order, rows, indent):
    flat = [value for row in rows for value in row]
    return (f'{indent}Cascade(\n'
            f'{indent}    name: "{name}", response: .{response}, sampleRate: {sample_rate!r}, cutoff: {cutoff!r}, order: {order},\n'
            f'{indent}    coefficients: [\n{swift_doubles(flat, indent + "        ", 5)}\n{indent}    ])')


def main():
    versions = _oracle.versions()
    out = []
    out.append("// Generated by Tests/Golden/generators/c_kernel_fixtures.py with "
               f"numpy {versions['numpy']} and scipy {versions['scipy']}.")
    out.append("// Do not edit by hand: change the generator and run it again with python3.")
    out.append("")
    out.append("/// Reference values for the tests of the C kernels, from SciPy (STG-2).")
    out.append("enum KernelFixtures {")
    out.append("    enum Response: String, Sendable { case lowPass, highPass }")
    out.append("")
    out.append("    /// A Butterworth cascade as `scipy.signal.butter(N:Wn:btype:analog:output:fs:)` returns it with")
    out.append("    /// `output='sos'`: the sections in SciPy's order, the poles nearest the unit circle last.")
    out.append("    struct Cascade: Sendable {")
    out.append("        let name: String")
    out.append("        let response: Response")
    out.append("        let sampleRate: Double")
    out.append("        let cutoff: Double")
    out.append("        let order: Int")
    out.append("        /// b0 b1 b2 a1 a2 per section (a0 = 1).")
    out.append("        let coefficients: [Double]")
    out.append("        var sections: Int { coefficients.count / 5 }")
    out.append("    }")
    out.append("")

    out.append("    /// The filters named in the acceptance cells of WP-208 and WP-209, and the orders of E-30.")
    out.append("    static let acceptance: [Cascade] = [")
    for name, response, sample_rate, cutoff, order in ACCEPTANCE:
        _, rows = butterworth(response, sample_rate, cutoff, order)
        out.append(cascade_literal(name, response, sample_rate, cutoff, order, rows, "        ") + ",")
    out.append("    ]")
    out.append("")
    out.append("    /// The filters of the stress-fixture library (`StressFixture.filtersNearZero`, `.filtersNearNyquist`),")
    out.append("    /// under the names it gives them.")
    out.append("    static let stress: [Cascade] = [")
    reference_sos = None
    for name, response, sample_rate, cutoff, order in STRESS:
        sos, rows = butterworth(response, sample_rate, cutoff, order)
        if name == "hp-20Hz-96k-order8":
            reference_sos = sos
        out.append(cascade_literal(name, response, sample_rate, cutoff, order, rows, "        ") + ",")
    out.append("    ]")
    out.append("")

    _, response = signal.sosfreqz(sos=reference_sos, worN=numpy.asarray(RESPONSE_FREQUENCIES), whole=False, fs=96_000.0)
    out.append("    /// |H| of `hp-20Hz-96k-order8` from `scipy.signal.sosfreqz(sos:worN:whole:fs:)`: what the")
    out.append("    /// double-precision kernel is held to within 0.01 dB (WP-211).")
    out.append("    static let highPass20HzResponseFrequencies: [Double] = [")
    out.append(swift_doubles(RESPONSE_FREQUENCIES, "        ", 5))
    out.append("    ]")
    out.append("    static let highPass20HzResponseMagnitudes: [Double] = [")
    out.append(swift_doubles([abs(h) for h in response], "        ", 3))
    out.append("    ]")
    out.append("")

    out.append("    /// A Kaiser windowed sinc for a rate change by `factor`: `scipy.signal.kaiserord(ripple:width:)`, then")
    out.append("    /// `scipy.signal.firwin(numtaps:cutoff:width:window:pass_zero:scale:fs:)`. Unity gain at 0 Hz; the stop")
    out.append(f"    /// band starts at the new Nyquist frequency and is at least {REJECTION:g} dB down; the pass band reaches")
    out.append(f"    /// {PASS_BAND:g} of it. An odd number of taps, so the delay (count − 1) / 2 is whole.")
    out.append("    struct LowPass: Sendable {")
    out.append("        let factor: Int")
    out.append("        let beta: Double")
    out.append("        /// The rejection SciPy measures from the new Nyquist frequency up, in dB.")
    out.append("        let rejection: Double")
    out.append("        let taps: [Double]")
    out.append("    }")
    out.append("")
    out.append("    static let lowPass: [LowPass] = [")
    for factor in FACTORS:
        count, beta, taps, achieved = kaiser_low_pass(factor)
        out.append(f"        LowPass(factor: {factor}, beta: {beta!r}, rejection: {achieved!r}, taps: [")
        out.append(swift_doubles(taps, "            ", 4))
        out.append("        ]),")
    out.append("    ]")
    out.append("}")
    out.append("")

    with open(OUTPUT, "w") as handle:
        handle.write("\n".join(out))
    print(f"wrote {os.path.relpath(OUTPUT, _golden.ROOT)}")


if __name__ == "__main__":
    main()
