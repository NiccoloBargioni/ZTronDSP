% Every kind of statement the static check reads, in a script that runs under GNU Octave.
frame = 8;
rate = 8000;
t = (0:frame-1) / rate;
x = [1 -2 0.5 3; 4 5 -6 7];
y = x(2, :) * 2 - 1;
z = [0.5+0.5i 0.5-0.5i -1+0i];
circle = cos(linspace(0, 2 * pi, 9));
power = sin(linspace(0, 2 * pi, 9)) .^ 2;
undefined = [1 NaN Inf -Inf];
decades = 10 .^ (0:3);
level = 20 * log10(abs(fft(t)) + 1e-300); % a comment after a statement
column = x(1, 2:3)';
halves = [column column] ./ 2;
picture = [1 2 3; 4 5 6];
% The plots: a comment between statements.
subplot(3, 2, 1);
plot(t, level, 'b-');
hold on;
plot(t, level - 3, 'r--');
stem(t, level, 'x');
hold off;
grid on;
xlabel('time (s)');
ylabel('level (dB)');
title('It''s every statement');
axis([0 0.001 -400 50]);
subplot(3, 2, 2);
semilogx(decades, y);
grid off;
xlabel('frequency (Hz)');
ylabel('value');
subplot(3, 2, 3);
loglog(decades, decades .^ 2, 'ko:');
hold on;
loglog(decades, decades, 's');
hold off;
xlabel('size (elements)');
ylabel('time (ns)');
axis tight;
subplot(3, 2, 4);
imagesc(1:3, [10 20], picture);
axis xy;
colorbar;
xlabel('column');
ylabel('frequency (Hz)');
subplot(3, 2, 5);
plot(real(z), imag(z), 'o');
hold('on');
plot(circle, power, 'k:');
plot(1:2, halves);
hold off;
grid('on');
axis equal;
xlabel('real part');
ylabel('imaginary part');
title('Roots');
