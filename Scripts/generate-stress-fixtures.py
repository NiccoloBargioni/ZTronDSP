#!/usr/bin/env python3
"""Writes Sources/ZTronDSPTesting/StressFixtureData.swift: the numbers behind the stress
fixtures of WP-016. Exact rational arithmetic throughout, so the documented condition numbers
are those of the stored polynomials, not of an approximation.

    python3 Scripts/generate-stress-fixtures.py
"""
from fractions import Fraction
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "Tests", "Golden", "generators"))
import _oracle  # noqa: E402

numpy, scipy = _oracle.load()
from scipy import signal  # noqa: E402

OUT = os.path.join(HERE, "..", "Sources", "ZTronDSPTesting", "StressFixtureData.swift")


def cmul(a, b):
    return (a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0])


def expand(roots):
    """Coefficients, highest power first, of prod (x - r) for complex roots given as exact pairs."""
    poly = [(Fraction(1), Fraction(0))]
    for r in roots:
        nxt = poly + [(Fraction(0), Fraction(0))]
        for i, c in enumerate(poly):
            m = cmul(c, r)
            nxt[i + 1] = (nxt[i + 1][0] - m[0], nxt[i + 1][1] - m[1])
        poly = nxt
    return poly


def evaluate(coefficients, x):
    acc = (Fraction(0), Fraction(0))
    for c in coefficients:
        acc = cmul(acc, x)
        acc = (acc[0] + c[0], acc[1] + c[1])
    return acc


def derivative(coefficients):
    n = len(coefficients) - 1
    return [(c[0] * (n - i), c[1] * (n - i)) for i, c in enumerate(coefficients[:-1])]


def magnitude(z):
    return math.hypot(float(z[0]), float(z[1]))


def condition(coefficients, root):
    """kappa(r) = sum |a_k| |r|^k / (|r| |p'(r)|) (specification 6.3.8)."""
    n = len(coefficients) - 1
    r = magnitude(root)
    numerator = sum(magnitude(c) * r ** (n - i) for i, c in enumerate(coefficients))
    slope = magnitude(evaluate(derivative(coefficients), root))
    if slope == 0 or r == 0:
        return float("inf")
    return numerator / (r * slope)


def swift_doubles(values):
    return "[" + ", ".join(repr(float(v)) for v in values) + "]"


def polynomial_case(name, roots, hazard, accuracy, multiplicity=1):
    exact = [(Fraction(r.real), Fraction(r.imag)) for r in roots]
    coefficients = expand(exact)
    assert all(abs(float(c[1])) < 1e-9 * max(1.0, abs(float(c[0]))) for c in coefficients), name
    stored = [float(c[0]) for c in coefficients]
    kappas = [condition(coefficients, r) for r in exact]
    finite = [k for k in kappas if math.isfinite(k)]
    worst = max(finite) if finite else float("inf")
    worst_text = repr(worst) if math.isfinite(worst) else ".infinity"
    return (
        f"    static let {name} = StressFixture.PolynomialCase(\n"
        f"        name: \"{name}\",\n"
        f"        coefficients: {swift_doubles(stored)},\n"
        f"        rootsReal: {swift_doubles([r.real for r in roots])},\n"
        f"        rootsImaginary: {swift_doubles([r.imag for r in roots])},\n"
        f"        largestConditionNumber: {worst_text},\n"
        f"        multiplicity: {multiplicity},\n"
        f"        achievableAccuracy: {accuracy!r},\n"
        f"        hazard: \"{hazard}\")\n"
    )


def main():
    parts = []
    parts.append("// Generated by Scripts/generate-stress-fixtures.py — do not edit by hand.\n")
    parts.append(f"// numpy {numpy.__version__}, scipy {scipy.__version__}. Exact rational arithmetic on the stored roots.\n\n")
    parts.append("enum StressFixtureData {\n")

    # 1. Wilkinson, degree 20: roots 1 … 20.
    parts.append(polynomial_case(
        "wilkinson20", [complex(k) for k in range(1, 21)],
        "Wilkinson's polynomial: evenly spaced real roots whose coefficients reach 20! and are no longer exact in "
        "double precision; the roots near 14–16 have condition numbers above 1e13.", 1e-3))

    # 2. Expanded order-16 Butterworth low-pass denominator, 1 kHz at 48 kHz.
    z, p, k = signal.butter(16, 1000.0, btype="low", analog=False, output="zpk", fs=48000.0)
    order = numpy.lexsort((p.imag, p.real))
    parts.append(polynomial_case(
        "butterworth16Expanded", [complex(v) for v in p[order]],
        "The denominator of an order-16 Butterworth low-pass at 1 kHz / 48 kHz, expanded into coefficients: "
        "sixteen poles clustered near z = 1, which is why designs stay in zero-pole-gain form (REAL-1).", 1e-1))

    # 3. A triple root: (x - 0.5)^3 (x + 0.25).
    parts.append(polynomial_case(
        "tripleRoot", [0.5 + 0j, 0.5 + 0j, 0.5 + 0j, -0.25 + 0j],
        "A root of multiplicity three: recoverable only to about epsilon^(1/3), roughly 6e-6.", 1e-4, multiplicity=3))

    # 4. Well-conditioned polynomials (kappa <= 1e4).
    well = {
        "wellQuadratic": [0.3 + 0.4j, 0.3 - 0.4j],
        "wellCubic": [-0.9 + 0j, 0.2 + 0.7j, 0.2 - 0.7j],
        "wellQuintic": [0.9 + 0j, -0.5 + 0.5j, -0.5 - 0.5j, 0.1 + 0.8j, 0.1 - 0.8j],
        "wellOctic": [0.8 * complex(math.cos(a), math.sin(a)) for a in
                      (0.4, -0.4, 1.1, -1.1, 1.9, -1.9, 2.7, -2.7)],
        "wellSpread": [2.0 + 0j, -1.5 + 0j, 0.5 + 0j, -0.25 + 0j, 3.0 + 1.0j, 3.0 - 1.0j],
    }
    for name, roots in well.items():
        parts.append(polynomial_case(name, roots, "Well-conditioned: every root has a condition number at or below 1e4.", 1e-10))

    parts.append("}\n")
    with open(OUT, "w") as f:
        f.write("".join(parts))
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
