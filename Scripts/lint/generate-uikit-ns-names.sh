#!/bin/bash
# Regenerates Scripts/lint/uikit-ns-names.txt: the `NS…` names that UIKit declares (UB-5).
#
# The list is committed; the lint reads the committed file and never the SDK. Run this when the
# SDK changes and review the difference.
#
#   Scripts/lint/generate-uikit-ns-names.sh [--sdk iphonesimulator]
#
# A name is on the list when a UIKit header declares it as a class, protocol, struct, enum,
# option set, typed constant type or typedef, or as an extern constant or function. Names that
# Foundation, CoreFoundation, CoreGraphics, CoreText, QuartzCore or the Objective-C runtime
# declare are left out: naming those is not naming UIKit.

set -eu
SDK_NAME="iphonesimulator"
if [ "${1:-}" = "--sdk" ] && [ -n "${2:-}" ]; then SDK_NAME="$2"; fi
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SDK="$(xcrun --sdk "$SDK_NAME" --show-sdk-path)"

python3 - "$SDK" "$HERE/uikit-ns-names.txt" <<'PY'
import os
import re
import sys

sdk, output = sys.argv[1], sys.argv[2]
frameworks = os.path.join(sdk, "System", "Library", "Frameworks")

# What may stand between a declared name and its semicolon: availability and Swift annotations.
ANNOTATIONS = r"(?:\s*[A-Z][A-Z0-9_]+(?:\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\))?)*\s*;"
DECLARATIONS = [
    re.compile(r"@interface\s+(NS[A-Z]\w*)\s*(?:<[^>]*>\s*)?:"),            # a class with a superclass, not a category
    re.compile(r"@protocol\s+(NS[A-Z]\w*)\s*(?:<|$)", re.MULTILINE),
    re.compile(r"NS_(?:ENUM|OPTIONS|CLOSED_ENUM|ERROR_ENUM)\s*\(\s*[^,()]+,\s*(NS[A-Z]\w*)\s*\)"),
    re.compile(r"typedef\s+[^;{}]*?\b(NS[A-Z]\w*)" + ANNOTATIONS),
    re.compile(r"\}\s*(NS[A-Z]\w*)" + ANNOTATIONS),
    re.compile(r"(?:UIKIT_EXTERN|FOUNDATION_EXTERN|extern)\s+[^;(){}]*?\b(NS[A-Z]\w*)" + ANNOTATIONS),
    re.compile(r"(?:UIKIT_EXTERN|UIKIT_STATIC_INLINE|FOUNDATION_EXTERN)\s+[^;(){}]*?\b(NS[A-Z]\w*)\s*\("),
]


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.DOTALL)
    return re.sub(r"//[^\n]*", " ", text)


def declared(framework):
    names = set()
    headers = os.path.join(frameworks, framework + ".framework", "Headers")
    if not os.path.isdir(headers):
        return names
    for directory, _, files in os.walk(headers):
        for name in files:
            if not name.endswith(".h"):
                continue
            with open(os.path.join(directory, name), encoding="utf-8", errors="replace") as handle:
                text = strip_comments(handle.read())
            for pattern in DECLARATIONS:
                names.update(pattern.findall(text))
    return names


uikit = declared("UIKit")
if not uikit:
    sys.exit("no UIKit headers under " + frameworks)
elsewhere = set()
for framework in ("Foundation", "CoreFoundation", "CoreGraphics", "CoreText", "QuartzCore", "CoreData", "CoreImage"):
    elsewhere |= declared(framework)
names = sorted(uikit - elsewhere)

with open(output, "w", encoding="utf-8") as handle:
    handle.write("# The NS… names that UIKit declares (UB-5). No file under Sources/ names one of them.\n")
    handle.write("# Generated by Scripts/lint/generate-uikit-ns-names.sh from the %s SDK; committed, and read as it is.\n" % os.path.basename(sdk))
    handle.write("# One name per line.\n")
    for name in names:
        handle.write(name + "\n")
print("%d names written to %s" % (len(names), output))
PY
