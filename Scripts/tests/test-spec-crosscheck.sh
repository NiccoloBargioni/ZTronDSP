#!/bin/bash
# Self-test of Scripts/spec-crosscheck.sh.
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
. "$ROOT/Scripts/tests/lib.sh"
FIXTURES="$ROOT/Tests/Fixtures/SpecCrosscheck"
CHECK="$ROOT/Scripts/spec-crosscheck.sh"

echo "spec-crosscheck"
expect_status 0 "a consistent specification passes" "$CHECK" "$FIXTURES/clean.md"
expect_contains "it counts packages and rows" "Read 7 packages in 6 rows"
expect_contains "a name that exists only as parts is a note" "WP-905 exists only as its parts WP-905a…b"
expect_contains "the name of a split that has not happened is a note" "WP-002a is a part of WP-002 that §12 does not define"
expect_contains "the reading of 'all' is stated" "is read as every package of M0…M8"
expect_lacks "a pipe inside a code span does not split a cell" "cells, expected 6"

expect_status 1 "a specification with defects fails" "$CHECK" "$FIXTURES/defects.md"
expect_contains "wrong counts" "[counts] the specification claims 9 packages in 8 rows; §12 holds 7 packages in 8 rows"
expect_contains "duplicate identifier" "[duplicate] WP-003 is defined on line"
expect_contains "dangling dependency" "[dangling dependency] WP-002 (line 26): dependency 555: WP-555 does not exist"
expect_contains "dangling range end" "range 001–444: end point WP-444 does not exist"
expect_contains "dependency that is not an identifier" "dependency 'soon' is not an identifier"
expect_contains "dependency cycle" "[cycle] dependency cycle: WP-001 → WP-004 → WP-001"
expect_contains "two equal lenses" "WP-002 (line 26): lenses 'A, A' are not two distinct letters"
expect_contains "an unknown lens" "lenses 'T, X' are not two distinct letters"
expect_contains "a single lens" "lenses 'N' are not two distinct letters"
expect_contains "unknown tag" "tag 'BOGUS' is neither ALG nor OPT"
expect_contains "malformed identifier" "[parse] line 30: malformed package identifier 'WP-0x5'"
expect_contains "row with the wrong number of cells" "[parse] line 31: row has 5 cells, expected 6"
expect_contains "requirement naming a missing package" "[traceability] R-01 (line 9) names WP-777: WP-777 does not exist"
expect_contains "requirement numbers out of order" "requirement numbers are not R-01…R-02 in order"
expect_contains "milestone table that disagrees with its section" "M0 is given as WP-001…009, its section runs from WP-001 to WP-004"
expect_contains "reference elsewhere to a missing package" "[reference] line 42 names WP-888: WP-888 does not exist"
expect_contains "range whose end is missing" "WP-001…999: range end WP-999 does not exist"
expect_contains "OPT triggers that disagree with the tags" "[OPT triggers] packages tagged OPT are WP-004; triggers are listed for WP-001"
expect_contains "a mandatory package that waits for an optional one" "[optional dependency] WP-001 (line 25) depends on WP-004, which is OPT"
expect_contains "a wait for a later milestone that is not announced" "[unannounced wait] WP-003 (M0, line 27) depends on WP-101"

expect_status 2 "a missing file is a usage error" "$CHECK" "$FIXTURES/absent.md"
expect_status 0 "the real specification has no defect" "$CHECK"
finish
